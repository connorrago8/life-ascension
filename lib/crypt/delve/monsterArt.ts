/** Monster sprites for the delve. `.` is empty. Each grid is validated on load. */
export const MONSTER_PALETTE: Record<string, string> = {
  k: '#14171b', d: '#2b2f37', s: '#8b949e', w: '#eef1f4', r: '#b9a79a', n: '#6a5e58',
  e: '#ff5a4f', y: '#ffd35a', g: '#5e8f5a', G: '#33522f', v: '#7a5bd1', V: '#bfa8ff',
  c: '#9fe6ff', C: '#e7fbff', b: '#4a3018', o: '#3c4450', p: '#2a2238', P: '#5a3f8a',
};

function grid(art: string): readonly string[] {
  const rows = art.split('\n').map((row) => row.trim()).filter(Boolean);
  const width = rows[0]?.length ?? 0;
  for (const row of rows) {
    if (row.length !== width) throw new Error(`Monster row has ${row.length}, expected ${width}: ${row}`);
    for (const ink of row) if (ink !== '.' && !MONSTER_PALETTE[ink]) throw new Error(`Unknown ink ${ink}`);
  }
  return rows;
}

