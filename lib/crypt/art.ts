function grid(art: string): readonly string[] {
  const rows = art.split('\n').map((row) => row.trim()).filter((row) => row.length > 0);
  const width = rows[0]?.length ?? 0;
  if (width === 0) throw new Error('Sprite is empty');
  for (const row of rows) {
    if (row.length !== width) {
      throw new Error(`Sprite row has ${row.length}, expected ${width}: ${row}`);
    }
    for (const ink of row) {
      if (ink !== '.' && !CRYPT_PALETTE[ink]) throw new Error(`Unknown sprite ink "${ink}"`);
    }
  }
  return rows;
}

